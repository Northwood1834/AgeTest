import {createHash} from "node:crypto";
import {readdir,readFile,writeFile} from "node:fs/promises";
import {fileURLToPath,pathToFileURL} from "node:url";
import path from "node:path";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const gamesDir=path.join(root,"src/games"),output=path.join(root,"src/game-manifest.js");
const required=["id","introducedIn","tier","flavor","step","family","category"];
const categories=new Set(["reaction","memory","language","spatial","prediction","inhibition","calculation","attention","timing","social"]);
const flavors=new Set(["classic","satisfying","quirky","wild"]);

function validateMetadata(metadata,file){
  const issues=[];
  if(!metadata||typeof metadata!=="object")return[`${file}: missing metadata`];
  required.forEach(field=>{if(metadata[field]===undefined||metadata[field]===null||metadata[field]==="")issues.push(`${file}: missing ${field}`)});
  if(typeof metadata.id!=="string"||!/^[-a-z0-9]+-v\d+$/.test(metadata.id))issues.push(`${file}: invalid id`);
  if(metadata.id&&`${metadata.id}.js`!==file)issues.push(`${file}: filename must match id`);
  if(typeof metadata.introducedIn!=="string"||!/^\d+\.\d+$/.test(metadata.introducedIn))issues.push(`${file}: invalid introducedIn`);
  if(!Number.isInteger(metadata.tier)||metadata.tier<1||metadata.tier>5)issues.push(`${file}: tier must be 1-5`);
  if(!flavors.has(metadata.flavor))issues.push(`${file}: invalid flavor`);
  if(!Number.isInteger(metadata.step)||metadata.step<1)issues.push(`${file}: step must be a positive integer`);
  if(!categories.has(metadata.category))issues.push(`${file}: invalid category`);
  const match=typeof metadata.id==="string"&&metadata.id.match(/^(.*)-v(\d+)$/);
  if(match&&(metadata.family!==match[1]||metadata.step!==Number(match[2])))issues.push(`${file}: family/step must match the stable id`);
  return issues;
}

async function build(){
  const files=(await readdir(gamesDir)).filter(file=>file.endsWith(".js")).sort(),entries=[],issues=[],ids=new Set();
  for(const file of files){
    const full=path.join(gamesDir,file),source=await readFile(full,"utf8"),namespace=await import(`${pathToFileURL(full).href}?manifest=${createHash("sha1").update(source).digest("hex")}`),metadata=namespace.default?.metadata;
    issues.push(...validateMetadata(metadata,file));
    if(metadata?.id){if(ids.has(metadata.id))issues.push(`${file}: duplicate id ${metadata.id}`);ids.add(metadata.id)}
    entries.push({...metadata,module:`./games/${file}`,hash:createHash("sha256").update(source).digest("hex").slice(0,16)});
  }
  if(!files.length)issues.push("no game modules found");
  if(issues.length)throw new Error(issues.join("\n"));
  const text=`// Generated by tools/build-game-manifest.mjs. Do not edit.\nexport const gameManifest=Object.freeze(${JSON.stringify(entries,null,2)}.map(Object.freeze));\n`;
  return text;
}

const expected=await build(),check=process.argv.includes("--check");
if(check){
  let actual="";try{actual=await readFile(output,"utf8")}catch{}
  if(actual!==expected){console.error("src/game-manifest.js is stale; run npm run build:games");process.exitCode=1}
}else{
  await writeFile(output,expected);console.log(`wrote ${path.relative(root,output)}`);
}
